import ExcelJS from 'exceljs';
import type { ReportColumn, StatusCell } from '@nacta/shared';
import { fmtGenerated, ink, legendLabel, tint } from './common';
import { logoPng } from './assets';
import type { Generator, ReportData, Row } from './types';

export const XLSX_MIME = 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet';
/** NACTA green for table headers (#065F46). */
export const REPORT_GREEN = '065F46';
const ORG = 'National Counter Terrorism Authority';
const FOOTER = 'Page &P of &N | NACTA Attendance | Confidential';
const MONO = 'Consolas';
const argb = (hex: string): string => `FF${hex.replace('#', '').toUpperCase()}`;

const isStatusCell = (v: unknown): v is StatusCell => typeof v === 'object' && v !== null && 'code' in v && 'label' in v;

/** "2026-11-24" -> a real Excel date (UTC midnight so the calendar day never shifts). */
function toExcelDate(s: string): Date {
  const [y, m, d] = s.split('-').map(Number) as [number, number, number];
  return new Date(Date.UTC(y, m - 1, d));
}
/** "09:03" / "09:03:12" -> fraction of a day. */
function toExcelTime(s: string): number {
  const [h, m, sec] = s.split(':').map(Number) as [number, number, number | undefined];
  return (h * 3600 + m * 60 + (sec ?? 0)) / 86400;
}

interface SheetSpec {
  name: string;
  title: string;
  subtitle: string;
  filters: string;
  columns: ReportColumn[];
  rows: Row[];
  totals: Row | null;
  highlights: { label: string; value: string }[];
  legend: StatusCell[];
  shade: Record<string, 'weekend' | 'holiday'>;
}

function columnWidth(c: ReportColumn, rows: Row[]): number {
  const longest = (cap: number) => {
    let n = 0;
    for (const r of rows) {
      const v = r[c.key];
      const len = isStatusCell(v) ? v.label.length : v === null || v === undefined ? 0 : String(v).length;
      if (len > n) n = len;
    }
    return Math.min(cap, n);
  };
  switch (c.kind) {
    case 'day_code': return 4.6;
    case 'mono': return Math.max(10, longest(16) + 3);
    case 'date': return 13.5;
    case 'time': return 10;
    case 'minutes':
    case 'hours': return 11;
    case 'percent': return 11;
    case 'number': return c.key.startsWith('t') && c.key.length <= 8 && c.label.length <= 12 ? 9.5 : 12;
    case 'status': return Math.max(14, longest(40) + 4);
    default: return Math.max(12, Math.min(42, Math.max(longest(42) + 3, Math.min(c.label.length + 2, 20))));
  }
}

function renderSheet(wb: ExcelJS.Workbook, logoId: number, spec: SheetSpec, gen: Generator, isMain: boolean): ExcelJS.Worksheet {
  const n = spec.columns.length;
  const ws = wb.addWorksheet(spec.name.slice(0, 31), { properties: { tabColor: { argb: argb(REPORT_GREEN) } }, views: [{ showGridLines: false }] });
  spec.columns.forEach((c, i) => {
    ws.getColumn(i + 1).width = columnWidth(c, spec.rows);
  });
  if ((ws.getColumn(1).width ?? 0) < 11) ws.getColumn(1).width = 11;

  const textFrom = 2;
  const merge = (row: number, from = textFrom) => {
    if (n > from) ws.mergeCells(row, from, row, n);
    return ws.getCell(row, from);
  };

  // ---- header block ----
  ws.addImage(logoId, {
    tl: { col: 0.12, row: 0.12 },
    ext: { width: 66, height: 66 },
  });
  const heights = [17, 26, 17, 15, 15];
  heights.forEach((h, i) => (ws.getRow(i + 1).height = h));
  const org = merge(1);
  org.value = ORG;
  org.font = { name: 'Calibri', size: 11, bold: true, color: { argb: argb(REPORT_GREEN) } };
  org.alignment = { vertical: 'middle' };
  const title = merge(2);
  title.value = spec.title;
  title.font = { name: 'Calibri', size: 17, bold: true, color: { argb: 'FF111827' } };
  title.alignment = { vertical: 'middle' };
  const sub = merge(3);
  sub.value = spec.subtitle;
  sub.font = { name: 'Calibri', size: 11, color: { argb: 'FF374151' } };
  sub.alignment = { vertical: 'middle' };
  const fil = merge(4);
  fil.value = spec.filters;
  fil.font = { name: 'Calibri', size: 9.5, color: { argb: 'FF4B5563' } };
  fil.alignment = { vertical: 'middle' };
  const genCell = merge(5);
  genCell.value = `Generated by ${gen.name} on ${fmtGenerated(gen.at)}`;
  genCell.font = { name: 'Calibri', size: 9.5, italic: true, color: { argb: 'FF6B7280' } };
  genCell.alignment = { vertical: 'middle' };
  for (let c = 1; c <= n; c++) {
    ws.getCell(5, c).border = { bottom: { style: 'medium', color: { argb: argb(REPORT_GREEN) } } };
  }

  // ---- highlights ribbon ----
  let row = 6;
  if (spec.highlights.length) {
    ws.mergeCells(row, 1, row, n);
    const cell = ws.getCell(row, 1);
    const richText: ExcelJS.RichText[] = [];
    spec.highlights.forEach((h, i) => {
      if (i) richText.push({ text: '      ', font: { size: 11, color: { argb: 'FFD1D5DB' } } });
      richText.push({ text: `${h.label}: `, font: { name: 'Calibri', size: 10, color: { argb: 'FF4B5563' } } });
      richText.push({ text: h.value, font: { name: 'Calibri', size: 11, bold: true, color: { argb: argb(REPORT_GREEN) } } });
    });
    cell.value = { richText };
    cell.alignment = { vertical: 'middle', wrapText: true, indent: 1 };
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFF0FDF4' } };
    const approxChars = spec.highlights.reduce((s, h) => s + h.label.length + h.value.length + 8, 0);
    const widthChars = spec.columns.reduce((s, _c, i) => s + (ws.getColumn(i + 1).width ?? 10), 0);
    ws.getRow(row).height = 22 * Math.max(1, Math.ceil(approxChars / Math.max(40, widthChars * 0.95)));
  }
  row += 2; // blank row, then the table

  // ---- table header ----
  const hasGroup = spec.columns.some((c) => c.group);
  const groupRow = hasGroup ? row : 0;
  const headerRow = hasGroup ? row + 1 : row;
  const headFill = { type: 'pattern' as const, pattern: 'solid' as const, fgColor: { argb: argb(REPORT_GREEN) } };
  const offFill = (k: 'weekend' | 'holiday' | undefined, fallback: string) => (k === 'weekend' ? '475569' : k === 'holiday' ? '0E7490' : fallback);
  if (hasGroup) {
    spec.columns.forEach((c, i) => {
      const cell = ws.getCell(groupRow, i + 1);
      cell.value = c.group ?? null;
      cell.font = { name: 'Calibri', size: 8, bold: true, color: { argb: 'FFD1FAE5' } };
      cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: argb(offFill(spec.shade[c.key], '065F46')) } };
      cell.alignment = { horizontal: 'center', vertical: 'middle' };
    });
    ws.getRow(groupRow).height = 14;
  }
  const longestLabel = Math.max(...spec.columns.map((c) => c.label.length / Math.max(4, (ws.getColumn(spec.columns.indexOf(c) + 1).width ?? 10))));
  ws.getRow(headerRow).height = longestLabel > 1.1 ? (longestLabel > 2.2 ? 44 : 32) : 24;
  spec.columns.forEach((c, i) => {
    const cell = ws.getCell(headerRow, i + 1);
    cell.value = c.label;
    cell.font = { name: 'Calibri', size: c.kind === 'day_code' ? 9 : 10.5, bold: true, color: { argb: 'FFFFFFFF' } };
    cell.fill = c.kind === 'day_code' && spec.shade[c.key]
      ? { type: 'pattern', pattern: 'solid', fgColor: { argb: argb(offFill(spec.shade[c.key], '065F46')) } }
      : headFill;
    const right = c.kind === 'number' || c.kind === 'minutes' || c.kind === 'hours' || c.kind === 'percent';
    cell.alignment = { horizontal: c.kind === 'day_code' || c.align === 'center' ? 'center' : right ? 'right' : 'left', vertical: 'middle', wrapText: true, indent: c.kind === 'day_code' ? 0 : 1 };
    cell.border = { bottom: { style: 'thin', color: { argb: 'FF044E3A' } } };
  });
  row = headerRow + 1;

  // ---- body ----
  const hair = { style: 'thin' as const, color: { argb: 'FFE5E7EB' } };
  spec.rows.forEach((r, ri) => {
    const zebra = ri % 2 === 1;
    spec.columns.forEach((c, ci) => {
      const cell = ws.getCell(row, ci + 1);
      writeCell(cell, c, r[c.key], spec.shade[c.key], zebra);
      cell.border = { bottom: hair };
    });
    row += 1;
  });

  // ---- totals ----
  if (spec.totals) {
    const labelKey = spec.columns.find((c) => c.kind === 'text' || c.kind === 'mono' || c.kind === 'date')?.key;
    spec.columns.forEach((c, ci) => {
      const cell = ws.getCell(row, ci + 1);
      const v = spec.totals?.[c.key];
      const isLabel = typeof v === 'string' && (c.kind === 'text' || c.kind === 'mono' || c.kind === 'date');
      if (isLabel) {
        cell.value = v;
        cell.alignment = { vertical: 'middle', horizontal: 'left', indent: 1 };
      } else if (typeof v === 'number') {
        cell.value = c.kind === 'percent' ? v / 100 : v;
        const fmt = numFmtOf(c);
        if (fmt) cell.numFmt = fmt;
        cell.alignment = { vertical: 'middle', horizontal: c.kind === 'day_code' ? 'center' : 'right', indent: c.kind === 'day_code' ? 0 : 1 };
      } else {
        cell.alignment = { vertical: 'middle' };
      }
      cell.font = { name: 'Calibri', size: c.kind === 'day_code' ? 9 : 10.5, bold: true, color: { argb: 'FF064E3B' } };
      cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFD1FAE5' } };
      cell.border = { top: { style: 'medium', color: { argb: argb(REPORT_GREEN) } }, bottom: { style: 'thin', color: { argb: argb(REPORT_GREEN) } } };
      if (c.key === labelKey && cell.value === null) cell.value = 'Total';
    });
    ws.getRow(row).height = 21;
    row += 1;
  }
  const lastTableRow = row - 1;

  // ---- legend ----
  if (spec.legend.length) {
    row += 1;
    const head = ws.getCell(row, 1);
    head.value = 'Legend';
    head.font = { name: 'Calibri', size: 10.5, bold: true, color: { argb: argb(REPORT_GREEN) } };
    row += 1;
    for (const l of spec.legend) {
      const chip = ws.getCell(row, 1);
      chip.value = l.code || '–';
      const color = l.color ?? '#64748B';
      chip.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: argb(tint(color)) } };
      chip.font = { name: 'Calibri', size: 10, bold: true, color: { argb: argb(ink(color)) } };
      chip.alignment = { horizontal: 'center', vertical: 'middle' };
      chip.border = { top: hair, left: hair, bottom: hair, right: hair };
      const lab = ws.getCell(row, 2);
      if (n > 2) ws.mergeCells(row, 2, row, Math.min(n, 7));
      lab.value = legendLabel(l);
      lab.font = { name: 'Calibri', size: 10, color: { argb: 'FF374151' } };
      lab.alignment = { vertical: 'middle', indent: 1 };
      row += 1;
    }
  }

  // ---- end of report ----
  row += 1;
  ws.mergeCells(row, 1, row, n);
  const end = ws.getCell(row, 1);
  end.value = `End of report · ${spec.rows.length.toLocaleString('en-US')} ${spec.rows.length === 1 ? 'record' : 'records'} · Confidential: for official use only`;
  end.font = { name: 'Calibri', size: 9, italic: true, color: { argb: 'FF6B7280' } };
  end.alignment = { horizontal: 'left', indent: 1 };
  const lastRow = row;

  // ---- freeze, filter, print ----
  ws.views = [{ state: 'frozen', xSplit: 0, ySplit: headerRow, showGridLines: false, topLeftCell: `A${headerRow + 1}` }];
  if (spec.rows.length) ws.autoFilter = { from: { row: headerRow, column: 1 }, to: { row: headerRow, column: n } };
  void lastTableRow;
  ws.pageSetup = {
    paperSize: 9, // A4
    orientation: 'landscape',
    fitToPage: true,
    fitToWidth: 1,
    fitToHeight: 0,
    horizontalCentered: true,
    margins: { left: 0.4, right: 0.4, top: 0.5, bottom: 0.6, header: 0.25, footer: 0.3 },
    printTitlesRow: `${hasGroup ? groupRow : headerRow}:${headerRow}`,
    printArea: `A1:${ws.getColumn(n).letter}${lastRow}`,
  };
  ws.headerFooter.oddFooter = `&C&8${FOOTER}`;
  ws.headerFooter.evenFooter = `&C&8${FOOTER}`;
  void isMain;
  return ws;
}

function numFmtOf(c: ReportColumn): string | undefined {
  switch (c.kind) {
    case 'minutes': return '#,##0';
    case 'hours': return '0.00';
    case 'percent': return '0.0%';
    case 'date': return 'dd mmm yyyy';
    default: return undefined;
  }
}

function writeCell(cell: ExcelJS.Cell, c: ReportColumn, v: unknown, shade: 'weekend' | 'holiday' | undefined, zebra: boolean): void {
  const base = { name: 'Calibri', size: 10, color: { argb: 'FF1F2937' } };
  const vertical = 'middle' as const;
  let fill: string | null = zebra ? 'F9FAFB' : null;
  if (shade) fill = shade === 'weekend' ? 'E2E8F0' : 'CFFAFE';

  if ((c.kind === 'status' || c.kind === 'day_code') && isStatusCell(v)) {
    const color = v.color ?? '#64748B';
    cell.value = c.kind === 'day_code' ? v.code : v.label;
    cell.font = { name: 'Calibri', size: c.kind === 'day_code' ? 9 : 10, bold: true, color: { argb: argb(ink(color)) } };
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: argb(tint(color)) } };
    cell.alignment = { horizontal: c.kind === 'day_code' ? 'center' : 'left', vertical, indent: c.kind === 'day_code' ? 0 : 1 };
    return;
  }
  if (fill) cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: argb(fill) } };
  if (v === null || v === undefined || v === '') {
    cell.font = base;
    return;
  }
  switch (c.kind) {
    case 'date':
      cell.value = typeof v === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(v) ? toExcelDate(v) : String(v);
      cell.numFmt = 'dd mmm yyyy';
      cell.font = base;
      cell.alignment = { horizontal: 'left', vertical, indent: 1 };
      break;
    case 'time':
      if (typeof v === 'string' && /^\d{2}:\d{2}(:\d{2})?$/.test(v)) {
        cell.value = toExcelTime(v);
        cell.numFmt = v.length > 5 ? 'hh:mm:ss' : 'hh:mm';
      } else cell.value = String(v);
      cell.font = { ...base, name: MONO, size: 10 };
      cell.alignment = { horizontal: 'center', vertical };
      break;
    case 'hours':
      // a real Excel duration (fraction of a day) shown as [h]:mm, so hours stay summable in Excel
      cell.value = Number(v) / 24;
      cell.numFmt = '[h]:mm';
      cell.font = base;
      cell.alignment = { horizontal: 'right', vertical, indent: 1 };
      break;
    case 'minutes':
    case 'number':
      cell.value = Number(v);
      if (numFmtOf(c)) cell.numFmt = numFmtOf(c) as string;
      cell.font = base;
      cell.alignment = { horizontal: 'right', vertical, indent: 1 };
      break;
    case 'percent':
      cell.value = Number(v) / 100;
      cell.numFmt = '0.0%';
      cell.font = base;
      cell.alignment = { horizontal: 'right', vertical, indent: 1 };
      break;
    case 'mono':
      cell.value = String(v);
      cell.numFmt = '@';
      cell.font = { ...base, name: MONO };
      cell.alignment = { horizontal: 'left', vertical, indent: 1 };
      break;
    case 'day_code':
      cell.value = typeof v === 'number' ? v : String(v);
      cell.font = { ...base, size: 9, bold: true };
      cell.alignment = { horizontal: 'center', vertical };
      break;
    default:
      cell.value = typeof v === 'object' ? JSON.stringify(v) : (v as string | number);
      cell.font = base;
      cell.alignment = { horizontal: c.align ?? 'left', vertical, wrapText: true, indent: c.align === 'center' ? 0 : 1 };
  }
}

/** The branded Excel workbook: header block, highlights, table, totals, legend; extra tables become their own sheets. */
export async function buildXlsx(d: ReportData, gen: Generator): Promise<Buffer> {
  const wb = new ExcelJS.Workbook();
  wb.creator = 'NACTA Attendance';
  wb.lastModifiedBy = gen.name;
  wb.company = ORG;
  wb.title = `${d.title} – ${d.subtitle}`;
  wb.subject = d.title;
  wb.created = gen.at;
  wb.modified = gen.at;
  const logoId = wb.addImage({ buffer: logoPng() as unknown as ExcelJS.Buffer, extension: 'png' });

  renderSheet(
    wb,
    logoId,
    {
      name: d.file.label.replace(/-/g, ' '),
      title: d.title,
      subtitle: d.subtitle,
      filters: d.filters,
      columns: d.columns,
      rows: d.rows,
      totals: d.totals,
      highlights: d.highlights,
      legend: d.legend,
      shade: d.columnShade,
    },
    gen,
    true,
  );
  for (const t of d.extraTables) {
    renderSheet(
      wb,
      logoId,
      {
        name: t.title,
        title: `${d.title} – ${t.title}`,
        subtitle: d.subtitle,
        filters: d.filters,
        columns: t.columns,
        rows: t.rows,
        totals: t.totals,
        highlights: [],
        legend: [],
        shade: {},
      },
      gen,
      false,
    );
  }
  return Buffer.from(await wb.xlsx.writeBuffer());
}
